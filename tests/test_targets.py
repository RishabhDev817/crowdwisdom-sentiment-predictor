def test_get_feature_columns_excludes_prohibited_and_targets(synthetic_ten_day_aligned_df):
    """
    Verifies that get_feature_columns strictly excludes:
      - Future target columns (starting with 'target_' or containing 'forward_return')
      - Raw price levels (Close, Open, High, Low)
      - Identifiers, URLs, raw text, and metadata
      - Date index or column
    """
    dirty_df = synthetic_ten_day_aligned_df.copy()
    dirty_df["target_Close_n0"] = dirty_df["Close"]
    dirty_df["target_return_h1"] = 0.05
    dirty_df["forward_return_1"] = 0.05
    dirty_df["post_id"] = "syn_123"
    dirty_df["url"] = "https://twitter.com/test"
    dirty_df["text"] = "Sample raw text"
    dirty_df["is_synthetic"] = True
    dirty_df["Date"] = "2026-10-01"

    feature_cols = get_feature_columns(dirty_df)

    # Targets must be excluded
    for col in feature_cols:
        assert not col.startswith("target_"), f"Target column '{col}' leaked into feature columns!"
        assert "forward_return" not in col
        assert col not in {"post_id", "url", "text", "is_synthetic", "Date"}
        assert not col.startswith("_")

    # Raw nominal price levels must be strictly excluded from ML inputs
    assert "Close" not in feature_cols
    assert "Open" not in feature_cols
    assert "High" not in feature_cols
    assert "Low" not in feature_cols

    # Permissible stationary and sentiment feature columns must be present
    assert "Volume" in feature_cols
    assert "post_count" in feature_cols
    assert "sentiment_mean" in feature_cols
    assert "has_posts" in feature_cols


