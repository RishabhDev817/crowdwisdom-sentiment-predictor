def test_add_strategy_trade_target_hand_calculated():
    """
    Verifies strategy trade target construction against hand-calculated values:
        trade_return[t] = (Open[t+2] / Open[t+1]) - 1.0
    Attached to signal date D_t (observing features through Close[D_t]).
    """
    dates = pd.date_range("2026-10-01", periods=6, freq="D", tz="UTC")
    # Open prices:
    # t=0 (D0): Open=100.0 -> entry Open[1]=110.0, exit Open[2]=121.0 -> ret = +10.0%
    # t=1 (D1): Open=110.0 -> entry Open[2]=121.0, exit Open[3]=108.9 -> ret = -10.0%
    # t=2 (D2): Open=121.0 -> entry Open[3]=108.9, exit Open[4]=114.345 -> ret = +5.0%
    # t=3 (D3): Open=108.9 -> entry Open[4]=114.345, exit Open[5]=120.0 -> ret = (120/114.345)-1
    # t=4 (D4): Open=114.345 -> exit Open[6] is unobserved -> NaN
    # t=5 (D5): Open=120.0 -> entry Open[6] and exit Open[7] unobserved -> NaN
    df = pd.DataFrame({
        "Open": [100.0, 110.0, 121.0, 108.9, 114.345, 120.0],
        "Close": [105.0, 115.0, 118.0, 112.0, 118.0, 122.0],
    }, index=dates)

    res = add_strategy_trade_target(df, open_column="Open")

    assert "target_trade_return" in res.columns
    vals = res["target_trade_return"].values

    # Hand-calculated values
    assert np.isclose(vals[0], 0.10)
    assert np.isclose(vals[1], -0.10)
    assert np.isclose(vals[2], 0.05)
    expected_3 = (120.0 / 114.345) - 1.0
    assert np.isclose(vals[3], expected_3)

    # Exactly the last 2 rows evaluate to NaN
    assert np.isnan(vals[4])
    assert np.isnan(vals[5])
    assert res["target_trade_return"].isna().sum() == 2


