def test_add_forecast_targets_alignment(synthetic_ten_day_aligned_df):
    """
    Verifies that target shifting strictly satisfies:
      - n+0 equals current row Close (nowcast reference price) and 0.0 (return).
      - n+h forward return equals (Close_{t+h} / Close_t) - 1.0.
      - Exactly the last h rows evaluate to NaN for horizon h.
    """
    df = add_forecast_targets(synthetic_ten_day_aligned_df, horizons=[0, 1, 2, 3, 4, 5])
    closes = synthetic_ten_day_aligned_df["Close"].values

    # 1. Horizon n+0: Nowcast reference
    assert "target_Close_n0" in df.columns
    assert "target_return_h0" in df.columns
    assert (df["target_Close_n0"].values == closes).all()
    assert (df["target_return_h0"].values == 0.0).all()
    assert df["target_Close_n0"].isna().sum() == 0

    # 2. Horizons n+1 through n+5
    for h in range(1, 6):
        target_price_col = f"target_Close_n{h}"
        target_return_col = f"target_return_h{h}"

        assert target_price_col in df.columns
        assert target_return_col in df.columns

        # Verify values match forward close for observed rows
        target_price_vals = df[target_price_col].values
        assert (target_price_vals[:-h] == closes[h:]).all()

        # Verify forward return matches (Close_{t+h} / Close_t) - 1.0
        expected_returns = (closes[h:] / closes[:-h]) - 1.0
        assert np.allclose(df[target_return_col].values[:-h], expected_returns)

        # Verify exactly the last h rows are NaN
        assert df[target_price_col].isna().sum() == h
        assert df[target_return_col].isna().sum() == h
        assert np.isnan(target_price_vals[-h:]).all()
        assert np.isnan(df[target_return_col].values[-h:]).all()


