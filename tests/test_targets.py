def test_add_strategy_trade_target_validation_errors():
    """Verifies input validation on data types, empty dataframes, insufficient rows, and prices."""
    dates = pd.date_range("2026-10-01", periods=5, freq="D", tz="UTC")

    # Non-DataFrame
    with pytest.raises(TypeError, match="Expected pandas DataFrame"):
        add_strategy_trade_target("not_df")  # type: ignore

    # Empty DataFrame
    with pytest.raises(ValueError, match="Input DataFrame is empty"):
        add_strategy_trade_target(pd.DataFrame())

    # Fewer than 3 rows
    short_df = pd.DataFrame({"Open": [100.0, 105.0]}, index=dates[:2])
    with pytest.raises(ValueError, match="requires at least 3 rows"):
        add_strategy_trade_target(short_df)

    # Missing Open column
    no_open = pd.DataFrame({"Close": [100.0, 105.0, 110.0]}, index=dates[:3])
    with pytest.raises(KeyError, match="Open price column 'Open' not found"):
        add_strategy_trade_target(no_open)

    # Non-numeric Open column
    str_open = pd.DataFrame({"Open": ["100", "105", "110"]}, index=dates[:3])
    with pytest.raises(TypeError, match="must be numeric"):
        add_strategy_trade_target(str_open)

    # Non-positive prices (zero or negative)
    zero_open = pd.DataFrame({"Open": [100.0, 0.0, 110.0]}, index=dates[:3])
    with pytest.raises(ValueError, match="contains non-positive, NaN, or non-finite"):
        add_strategy_trade_target(zero_open)

    neg_open = pd.DataFrame({"Open": [100.0, -10.0, 110.0]}, index=dates[:3])
    with pytest.raises(ValueError, match="contains non-positive, NaN, or non-finite"):
        add_strategy_trade_target(neg_open)

    # NaN in Open prices
    nan_open = pd.DataFrame({"Open": [100.0, np.nan, 110.0]}, index=dates[:3])
    with pytest.raises(ValueError, match="contains non-positive, NaN, or non-finite"):
        add_strategy_trade_target(nan_open)

    # Calendar gap in dates
    gapped_dates = [dates[0], dates[1], dates[3]]  # Missing dates[2]
    gap_df = pd.DataFrame({"Open": [100.0, 105.0, 110.0]}, index=gapped_dates)
    with pytest.raises(ValueError, match="Calendar continuity violation"):
        add_strategy_trade_target(gap_df)


def test_strategy_target_distinct_from_close_to_close_target():
    """
    Verifies that the strategy target measures the executable holding period
    (Open.shift(-2)/Open.shift(-1) - 1.0) and is distinctly different from the
    close-to-close forecasting target (Close.shift(-1)/Close - 1.0).
    """
    dates = pd.date_range("2026-10-01", periods=4, freq="D", tz="UTC")
    df = pd.DataFrame({
        "Open": [100.0, 102.0, 110.0, 115.0],
        "Close": [101.0, 108.0, 112.0, 118.0],
    }, index=dates)

    df_targets = add_forecast_targets(df, horizons=[1])
    df_targets = add_strategy_trade_target(df_targets)

    # Row 0:
    # Forecasting target h=1: Close[1]/Close[0] - 1 = 108/101 - 1 = +6.93%
    # Strategy trade target: Open[2]/Open[1] - 1 = 110/102 - 1 = +7.84%
    c2c_ret = df_targets["target_return_h1"].iloc[0]
    trade_ret = df_targets["target_trade_return"].iloc[0]

    assert not np.isclose(c2c_ret, trade_ret)
    assert np.isclose(c2c_ret, (108.0 / 101.0) - 1.0)
    assert np.isclose(trade_ret, (110.0 / 102.0) - 1.0)

